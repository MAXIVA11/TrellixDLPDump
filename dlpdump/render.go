package main

import (
	"fmt"
	"sort"
	"strings"
)

// --- text renderer ----------------------------------------------------------

func renderText(r Report) {
	fmt.Printf("Trellix/McAfee DLP Endpoint  -  %s\n", r.InstallRoot)
	fmt.Println(strings.Repeat("=", 64))

	c := r.Config
	managed := "UNMANAGED (standalone)"
	if c.Managed {
		managed = "managed by ePO"
	}
	fmt.Println("Configuration")
	fmt.Printf("  Agent version     %s\n", c.AgentVersion)
	fmt.Printf("  Computer          %s\n", c.ComputerName)
	fmt.Printf("  Handlers loaded   %s\n", c.InstalledHdlrs)
	fmt.Printf("  Management        %s\n", managed)
	fmt.Printf("                    %s\n", c.EpoDetail)
	policy := "no active global policy found"
	if c.PolicyStore.GlobalPolicySeen {
		policy = "global policy present (GlobalPolicy.opg)"
	}
	fmt.Printf("  Policy            %s\n", policy)

	fmt.Println("\nServices")
	for _, s := range r.System.Services {
		pid := ""
		if s.PID != 0 {
			pid = fmt.Sprintf("  pid %d", s.PID)
		}
		fmt.Printf("  %-26s %-13s (%s)%s\n", s.Name, s.State, s.StartType, pid)
	}
	fmt.Println("Kernel drivers")
	for _, d := range r.System.Drivers {
		fmt.Printf("  %-16s %-10s %s\n", d.Name, d.State, d.Role)
	}

	if r.Health.Lines > 0 {
		fmt.Println("\nAgent health (from its service log)")
		if r.Health.Start != nil {
			fmt.Printf("  Last start        %s\n", r.Health.Start.Format("2006-01-02 15:04:05"))
		}
		fmt.Printf("  Policy            %s\n", r.Health.PolicyLoaded)
		fmt.Printf("  Management        %s\n", r.Health.Management)
		fmt.Printf("  Drivers           %s\n", strings.Join(r.Health.Drivers, ", "))
		if len(r.Health.Issues) > 0 {
			fmt.Printf("  Errors/warnings   %d distinct\n", len(r.Health.Issues))
			for i, is := range r.Health.Issues {
				if i >= 6 {
					fmt.Printf("    ... and %d more\n", len(r.Health.Issues)-6)
					break
				}
				msg := is.Message
				if len(msg) > 68 {
					msg = msg[:68] + "..."
				}
				fmt.Printf("    [%s x%d] %s: %s\n", strings.ToUpper(is.Severity[:1]), is.Count, is.Component, msg)
			}
		}
	}

	grp := groupByRole(r.Modules)
	fmt.Printf("\nComponents (%d files)\n", len(r.Modules))
	for _, role := range roleOrder {
		list := grp[role]
		if len(list) == 0 {
			continue
		}
		fmt.Printf("\n  %s - %s  [%d]\n", strings.ToUpper(string(role)), roleDesc[role], len(list))
		if role == RoleKeyView || role == RoleSupport {
			var bad []string
			for _, m := range list {
				if m.Signature != nil && m.Signature.Trust != "trusted" && m.Signature.Trust != "unsigned" {
					bad = append(bad, m.Name)
				}
			}
			fmt.Printf("    %d files", len(list))
			if len(bad) > 0 {
				fmt.Printf("; UNTRUSTED: %s", strings.Join(bad, ", "))
			}
			fmt.Println()
			continue
		}
		for _, m := range list {
			name := m.Name
			if m.Dir != "" {
				name = m.Dir + `\` + m.Name
			}
			desc := m.Description
			if desc == "" {
				desc = "-"
			}
			sig := sigCell(m)
			if sig != "" {
				sig = "[" + sig + "]"
			}
			fmt.Printf("    %-30s %-7s %s %s\n", name, kb(m.SizeKB), desc, sig)
		}
	}

	counts, n := trustCounts(r.Modules)
	if n > 0 {
		fmt.Printf("\n  Signatures checked: %d (%s)\n", n, countsStr(counts))
		if counts["untrusted"] > 0 {
			fmt.Println("  WARNING: untrusted binaries present - investigate.")
		}
	}
}

// --- markdown renderer ------------------------------------------------------

func renderMarkdown(r Report) string {
	var b strings.Builder
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	p("# Trellix DLP Endpoint — deployment dump\n\n")
	p("> Generated by `dlpdump` (read-only) from `%s`\n\n", r.InstallRoot)

	c := r.Config
	managed := "Unmanaged (standalone)"
	if c.Managed {
		managed = "Managed by ePO"
	}
	p("## Configuration\n\n")
	p("| Field | Value |\n|---|---|\n")
	p("| Agent version | `%s` |\n", c.AgentVersion)
	p("| Computer | `%s` |\n", c.ComputerName)
	p("| Handlers loaded | %s |\n", c.InstalledHdlrs)
	p("| Management | **%s** — %s |\n", managed, c.EpoDetail)
	policy := "none active"
	if c.PolicyStore.GlobalPolicySeen {
		policy = "GlobalPolicy.opg present"
	}
	p("| Policy | %s |\n\n", policy)

	p("## Services & kernel drivers\n\n")
	p("| Component | Kind | State | Role |\n|---|---|---|---|\n")
	for _, s := range r.System.Services {
		p("| `%s` | service | %s (%s) | main DLP service |\n", s.Name, s.State, s.StartType)
	}
	for _, d := range r.System.Drivers {
		p("| `%s` | driver | %s | %s |\n", d.Name, d.State, d.Role)
	}
	p("\n")

	if r.Health.Lines > 0 {
		p("## Health (from the agent's service log)\n\n")
		if r.Health.Start != nil {
			p("- **Last start:** %s\n", r.Health.Start.Format("2006-01-02 15:04:05"))
		}
		p("- **Policy:** %s\n", r.Health.PolicyLoaded)
		p("- **Management:** %s\n", r.Health.Management)
		p("- **Drivers:** %s\n", strings.Join(r.Health.Drivers, ", "))
		if len(r.Health.Issues) > 0 {
			p("\n| Severity | Component | Message | Count |\n|---|---|---|---|\n")
			for i, is := range r.Health.Issues {
				if i >= 10 {
					break
				}
				p("| %s | %s | %s | %d |\n", is.Severity, is.Component, strings.ReplaceAll(is.Message, "|", "\\|"), is.Count)
			}
		}
		p("\n")
	}

	p("## Components (%d files)\n\n", len(r.Modules))
	grp := groupByRole(r.Modules)
	for _, role := range roleOrder {
		list := grp[role]
		if len(list) == 0 {
			continue
		}
		p("### %s — %s  (%d)\n\n", strings.ToUpper(string(role)), roleDesc[role], len(list))
		if role == RoleKeyView || role == RoleSupport {
			names := make([]string, 0, len(list))
			for _, m := range list {
				names = append(names, "`"+m.Name+"`")
			}
			sort.Strings(names)
			p("%d files: %s\n\n", len(list), strings.Join(names, ", "))
			continue
		}
		p("| File | Size | Description | Signature |\n|---|---|---|---|\n")
		for _, m := range list {
			name := m.Name
			if m.Dir != "" {
				name = m.Dir + `\` + m.Name
			}
			desc := m.Description
			if desc == "" {
				desc = "-"
			}
			p("| `%s` | %s | %s | %s |\n", name, kb(m.SizeKB), desc, sigCell(m))
		}
		p("\n")
	}

	counts, n := trustCounts(r.Modules)
	if n > 0 {
		p("**Signatures checked:** %d — %s\n", n, countsStr(counts))
	}
	return b.String()
}

func countsStr(counts map[string]int) string {
	keys := make([]string, 0, len(counts))
	for k := range counts {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, fmt.Sprintf("%d %s", counts[k], k))
	}
	return strings.Join(parts, ", ")
}
